import assert from 'node:assert/strict';
import { updateRecharge, applyRecharge } from '../recharge.mjs';
const wallet=(balance,spent,currency='USD',scope='account')=>({balance,spent,currency,scope});
let first=updateRecharge(null,wallet(8,92),100);
assert.equal(first.state.baseline,8);assert.equal(first.ratio,1);
let consumed=updateRecharge(first.state,wallet(6,94),200);
assert.equal(consumed.state.baseline,8);assert.equal(consumed.ratio,.75);assert.equal(consumed.credited,false);
let topped=updateRecharge(consumed.state,wallet(15,95),300);
assert.equal(topped.state.baseline,15);assert.equal(topped.ratio,1);assert.equal(topped.state.lastCredit,10);
let mixed=updateRecharge(topped.state,wallet(14,98),400);
assert.equal(mixed.credited,true);assert.equal(mixed.state.baseline,14);assert.equal(mixed.state.lastCredit,2);
let spentAgain=updateRecharge(mixed.state,wallet(7,105),500);
assert.equal(spentAgain.state.baseline,14);assert.equal(spentAgain.ratio,.5);
let restored=updateRecharge(JSON.parse(JSON.stringify(spentAgain.state)),wallet(0,112),600);
assert.equal(restored.state.baseline,14);assert.equal(restored.ratio,0);
assert.equal(updateRecharge(restored.state,wallet(-1,113),700).ratio,0);
assert.equal(updateRecharge(restored.state,wallet(2,0,'CNY'),700).state.baseline,2);
const noCounter=updateRecharge(null,wallet(10,null),100);
assert.equal(updateRecharge(noCounter.state,wallet(7,null),200).state.baseline,10);
assert.equal(updateRecharge(noCounter.state,wallet(12,null),200).state.baseline,12);
assert.equal(updateRecharge(noCounter.state,wallet(10.00000001,null),200).credited,false);
assert.equal(updateRecharge(consumed.state,wallet(5,1),300).credited,false);
assert.equal(updateRecharge(null,wallet(0,5)).ratio,null);
const book={accounts:{a:first.state}};
const stale={status:'stale',wallet:wallet(999,1000),views:[{key:'balance',ratio:.2}]};
applyRecharge(stale,'a',book);assert.equal(book.accounts.a.baseline,8);
const ok={status:'ok',wallet:wallet(4,96),views:[{key:'balance',ratio:.04}],detail:'余额'};
applyRecharge(ok,'a',book);assert.equal(ok.views[0].ratio,.5);assert.equal(ok.views[0].baseline,8);
console.log('通过：首次当前余额、消费分母固定、充值重置、充值与消费同周期、重启恢复、零负余额、计数重置、未知消费、微小误差、缓存不更新基准。');
